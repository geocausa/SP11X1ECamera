#!/usr/bin/env python3
import csv, hashlib, json, re
from pathlib import Path
D=Path(__file__).resolve().parent
P1=D/'raw/E003_IMX681_CPHY_ORACLE_20260827.log'
P2=D/'raw/E003_IMX681_CPHY_ORACLE_20260827_PASS2.log'
BASE=0x0ace8000
pat=re.compile(r'^([0-9a-f]{8})`([0-9a-f]{8})\s+([0-9a-f]{8})\s+([0-9a-f]{8})\s+([0-9a-f]{8})\s+([0-9a-f]{8})\s*$',re.I|re.M)
def text(p): return p.read_text(encoding='utf-16')
def dump(t,start,end):
    s=t.rsplit(start,1)[1].split(end,1)[0]
    out={}
    for m in pat.finditer(s):
        a=int(m.group(1)+m.group(2),16)
        for i in range(4): out[a+4*i]=int(m.group(3+i),16)
    if len(out)!=2048: raise SystemExit(f'{start}: parsed {len(out)} dwords')
    return out
t1,t2=text(P1),text(P2)
idle=dump(t1,'===E003_IDLE_CSIPHY2_LOGGED_BEGIN===','===E003_IDLE_CSIPHY2_LOGGED_END===')
live1=dump(t1,'===E003_LIVE_CSIPHY2_BEGIN===','===E003_LIVE_CSIPHY2_END===')
post=dump(t1,'===E003_POSTSTOP_CSIPHY2_BEGIN===','===E003_POSTSTOP_CSIPHY2_END===')
live2=dump(t2,'===E003_PASS2_LIVE_CSIPHY2_BEGIN===','===E003_PASS2_LIVE_CSIPHY2_END===')
rows=[]
for a in sorted(live1):
    stable=live1[a]==live2[a]
    rows.append(dict(offset=f'0x{a-BASE:04x}',address=f'0x{a:08x}',idle=f'0x{idle[a]:08x}',live1=f'0x{live1[a]:08x}',live2=f'0x{live2[a]:08x}',post=f'0x{post[a]:08x}',stable_live=stable,stable_nonzero=stable and live1[a]!=0,changed_from_idle=idle[a]!=live1[a],returns_to_idle=idle[a]==post[a]))
stable=[r for r in rows if r['stable_nonzero']]
volatile=[r for r in rows if r['live1']!=r['live2']]
retbad=[r for r in rows if not r['returns_to_idle']]
for name,data in [('csiphy2-all-2048.csv',rows),('csiphy2-stable-nonzero.csv',stable),('csiphy2-live-volatile.csv',volatile)]:
    with (D/name).open('w',newline='') as f:
        w=csv.DictWriter(f,fieldnames=data[0].keys(),lineterminator='\n'); w.writeheader(); w.writerows(data)
banks={}
for r in stable:
    off=int(r['offset'],16); b=f'0x{(off//0x100)*0x100:04x}'; banks[b]=banks.get(b,0)+1
sha=lambda p: hashlib.sha256(p.read_bytes()).hexdigest()
summary=dict(date='2026-08-27',device='Surface Camera Front / Sony IMX681',csiphy2_base='0x0ace8000',csiphy2_size_bytes=8192,dwords_per_dump=2048,idle_post_mismatch=len(retbad),stable_nonzero_live=len(stable),volatile_live=len(volatile),bank_counts=banks,pass1_sha256=sha(P1),pass2_sha256=sha(P2))
(D/'oracle-summary.json').write_text(json.dumps(summary,indent=2)+'\n')
tlmm=[(100,'MCLK4/cam_aon','0x00000244/0x00000002','0x00000244/0x00000002','0x00000244/0x00000002'),(235,'CCI1/master1','0x00001800/0x00000000','0x00001a04/0x00000003','0x00001800/0x00000000'),(236,'CCI1/master1','0x00001800/0x00000000','0x00001a04/0x00000003','0x00001800/0x00000000'),(237,'IMX681 reset','0x00001a00/0x00000000','0x00001a00/0x00000003','0x00001a00/0x00000000')]
md=['# E003 IMX681 / X1E80100 Windows C-PHY oracle','', 'Date: 2026-08-27','', '## Acquisition','', '- SP11 Windows front device explicitly targeted as `Surface Camera Front` through WinRT `MediaCapture` / `MediaFrameReader`.','- `MediaFrameReader.StartAsync()` returned `Success` in two independent live passes.','- SP7 KDNET broke the running SP11 kernel and read physical MMIO.','- CSIPHY2 physical window: `0x0ace8000..0x0ace9fff` (8 KiB / 2048 dwords).','- Pass 1 captured idle -> live -> post-stop; pass 2 independently captured live again.','', '## Hard results','',f'- Post-stop equals idle across all 2048 dwords: **PASS** (mismatches: {len(retbad)}).',f'- Stable nonzero dwords across the two live captures: **{len(stable)}**.',f'- Live-variable dwords: **{len(volatile)}**.','- Stable nonzero bank distribution:']
md += [f'  - `{b}`: {banks[b]}' for b in sorted(banks)]
md += ['','The three 20-register blocks at offsets `0x0200`, `0x0600`, and `0x0a00` are bit-for-bit stable across both live captures. They are the strongest Windows-derived candidates for X1E80100 three-trio C-PHY electrical programming.','','## Dynamic TLMM proof','','| GPIO | Role | Idle ctl/io | Live ctl/io | Post-stop ctl/io |','|---:|---|---|---|---|']
md += [f'| {g} | {role} | `{i}` | `{l}` | `{p}` |' for g,role,i,l,p in tlmm]
md += ['','## Live-variable offsets','','| Offset | Pass 1 | Pass 2 |','|---:|---:|---:|']
md += [f"| `{r['offset']}` | `{r['live1']}` | `{r['live2']}` |" for r in volatile]
md += ['','These seven offsets are excluded from an initial static electrical-table candidate until their semantics are understood.','','## Raw-log integrity','',f"- pass 1 SHA-256: `{summary['pass1_sha256']}`",f"- pass 2 SHA-256: `{summary['pass2_sha256']}`",'','The raw UTF-16 KD transcripts are retained under `raw/`; all CSV/JSON results are mechanically regenerated by `extract_oracle.py`.']
(D/'WINDOWS-ORACLE.md').write_text('\n'.join(md)+'\n')
print(json.dumps(summary,indent=2))
print('volatile:',[(r['offset'],r['live1'],r['live2']) for r in volatile])
