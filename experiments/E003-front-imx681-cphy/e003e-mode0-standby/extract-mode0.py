#!/usr/bin/env python3
"""Extract SP11 IMX681 init + mode0 settings from the exact local QTI oracle.

The proprietary input is never copied into the repository. This script verifies its
known SHA-256 and emits only derived register/value evidence used for clean-room Linux
integration.
"""
from __future__ import annotations
import argparse,csv,hashlib,json,struct,sys
from pathlib import Path

EXPECTED_SHA='f7dd81be64153fd3f0da8e6288ee1b9906b7bf51b773a98496934d76dc96a45c'
FORBIDDEN={0x0100:'MODE_SELECT'}

def sha(p:Path): return hashlib.sha256(p.read_bytes()).hexdigest()
def scalar(e):
    b=bytes.fromhex(e['raw_hex'])
    if not b:return None
    return int.from_bytes(b,'little')
def u32s(e):
    b=bytes.fromhex(e['raw_hex'])
    if len(b)%4: raise SystemExit(f'{e["name"]} id={e["id"]}: non-u32 payload')
    return list(struct.unpack('<'+'I'*(len(b)//4),b))
def reg_list(e,ids):
    b=bytes.fromhex(e['raw_hex'])
    if len(b)%40: raise SystemExit(f'regSetting id={e["id"]}: bad size')
    out=[]
    for idx,off in enumerate(range(0,len(b),40)):
        w=struct.unpack('<10I',b[off:off+40])
        d=scalar(ids[w[4]]) if w[4] in ids else None
        delay=scalar(ids[w[9]]) if w[9] in ids else None
        out.append(dict(index=idx,address=w[2],data=d,addr_type=w[5],data_type=w[6],operation=w[7],delay_us=delay or 0,slave_override=w[0] or None))
    return out
def resolve_count_ref(e,ids,label):
    w=u32s(e)
    # resSettings is [count, ref]. initSettings is [stage, count, ref].
    if len(w)==2: count,ref=w
    elif len(w)==3: _,count,ref=w
    else: raise SystemExit(f'{label}: unexpected descriptor {w}')
    target=ids.get(ref)
    if not target or target['name'] not in ('regSetting','initSetting'):
        raise SystemExit(f'{label}: ref {ref} -> {target and target["name"]}')
    if target['name']=='initSetting':
        # The outer initSettings count is the number of initSetting blocks.
        # The nested initSetting carries the actual register count/ref pair.
        if count != 1: raise SystemExit(f'initSettings block count {count} != 1')
        iw=u32s(target)
        if len(iw)!=2: raise SystemExit('initSetting malformed')
        count,ref=iw; target=ids[ref]
    regs=reg_list(target,ids)
    if len(regs)!=count: raise SystemExit(f'{label}: count {count}, decoded {len(regs)}')
    return regs,target['id']
def check(regs,label):
    if any(r['operation']!=0 for r in regs): raise SystemExit(f'{label}: non-write operation')
    if any(r['addr_type']!=2 for r in regs): raise SystemExit(f'{label}: non-16-bit address type')
    if any(r['data_type']!=1 for r in regs): raise SystemExit(f'{label}: non-8-bit data type')
    if any(r['slave_override'] is not None for r in regs): raise SystemExit(f'{label}: slave override present')
    bad=[r for r in regs if r['address'] in FORBIDDEN]
    if bad: raise SystemExit(f'{label}: FORBIDDEN {FORBIDDEN[bad[0]["address"]]} write at index {bad[0]["index"]}')
    if any(r['data'] is None or not 0 <= r['data'] <= 0xff for r in regs): raise SystemExit(f'{label}: invalid 8-bit data')
def final_map(regs):
    d={}
    for r in regs:d[r['address']]=r['data']
    return d
def emit_c(path,init,mode):
    def arr(name,rs):
        q=[f'static const struct cci_reg_sequence {name}[] = {{']
        q += [f'\t{{ CCI_REG8(0x{r["address"]:04x}), 0x{r["data"]:02x} }},' for r in rs]
        q += ['};','']
        return q
    text=['/* SPDX-License-Identifier: GPL-2.0 */',
          '/* Machine-derived SP11 IMX681 standby tables; generated by extract-mode0.py. */',
          '/* Safety invariant: neither generated table contains MODE_SELECT. */','']
    text += arr('imx681_sp11_init_regs',init)
    text += arr('imx681_sp11_mode0_regs',mode)
    path.write_text('\n'.join(text))
def main():
    ap=argparse.ArgumentParser();ap.add_argument('oracle');ap.add_argument('--parser',required=True);ap.add_argument('--out',required=True);a=ap.parse_args()
    src=Path(a.oracle); out=Path(a.out); out.mkdir(parents=True,exist_ok=True)
    got=sha(src)
    if got!=EXPECTED_SHA: raise SystemExit(f'oracle SHA mismatch {got}')
    sys.path.insert(0,str(Path(a.parser).resolve().parent))
    import qti_parameter_bin as q
    o=q.parse(src);ids={e['id']:e for e in o['entries']}
    init_desc=next(e for e in o['entries'] if e['name']=='initSettings' and e['payload_size'])
    init,init_id=resolve_count_ref(init_desc,ids,'init')
    rd=next(e for e in o['entries'] if e['name']=='resolutionData' and e['payload_size'])
    rb=bytes.fromhex(rd['raw_hex'])
    if len(rb)%252: raise SystemExit('resolutionData element size')
    mode0=rb[:252]
    res_id=struct.unpack_from('<I',mode0,0x70)[0]
    if ids[res_id]['name']!='resSettings': raise SystemExit('mode0 resSettings ref')
    mode,mode_id=resolve_count_ref(ids[res_id],ids,'mode0')
    check(init,'init'); check(mode,'mode0')
    combined=init+mode; check(combined,'combined')
    # Cross-check the key mode0 geometry/timing fields from resolutionData.
    line=struct.unpack_from('<I',mode0,0x24)[0]; frame=struct.unpack_from('<I',mode0,0x28)[0]; pix=struct.unpack_from('<I',mode0,0x34)[0]
    stream_id=struct.unpack_from('<I',mode0,0x18)[0]; sw=u32s(ids[stream_id])
    # streamConfiguration contains refs/scalars; these offsets were mechanically established by qti_sensor_summary.
    sc=bytes.fromhex(ids[stream_id]['raw_hex']); scw=struct.unpack('<'+'I'*(len(sc)//4),sc)
    vc=scalar(ids[scw[1]]); dtype=scw[2]; x=scw[3]; y=scw[4]; width=scw[5]; height=scw[6]; bpp=scw[7]
    fm=final_map(combined)
    expected={0x0111:0x03,0x0112:0x0a,0x0113:0x0a,0x0114:0x00,0x0342:0x1a,0x0343:0x60,
              0x0344:0x00,0x0345:0x68,0x0346:0x01,0x0347:0x00,0x034c:0x0f,0x034d:0x00,0x034e:0x0a,0x034f:0x50,
              0x0301:0x06,0x0303:0x02,0x0305:0x02,0x0306:0x00,0x0307:0xe1,0x030d:0x03,0x030e:0x01,0x030f:0x77}
    mismatch={hex(k):(fm.get(k),v) for k,v in expected.items() if fm.get(k)!=v}
    if mismatch: raise SystemExit(f'key register mismatch {mismatch}')
    if (vc,dtype,x,y,width,height,bpp,line,frame,pix)!=(0,0x2b,104,256,3840,2640,10,6752,3554,548570000):
        raise SystemExit('mode0 metadata cross-check failed')
    summary=dict(oracle_sha256=got,init_regsetting_id=init_id,init_records=len(init),mode0_regsetting_id=mode_id,mode0_records=len(mode),
                 combined_records=len(combined),combined_unique_registers=len(final_map(combined)),mode_select_writes=sum(r['address']==0x0100 for r in combined),
                 group_hold_writes=sum(r['address']==0x0104 for r in combined),orientation_writes=sum(r['address']==0x0101 for r in combined),
                 mode0=dict(vc=vc,data_type=dtype,x_start=x,y_start=y,width=width,height=height,bpp=bpp,line_length=line,frame_length=frame,pixel_rate_hz=pix,fps=30),
                 camss_cphy_fallback_link_freq_hz=(pix*16*bpp)//(2*1*7),
                 key_final_registers={f'0x{k:04x}':fm[k] for k in expected})
    (out/'MODE0-SUMMARY.json').write_text(json.dumps(summary,indent=2)+'\n')
    for name,regs in [('init',init),('mode0',mode)]:
        with (out/f'{name}-registers.csv').open('w',newline='') as f:
            w=csv.DictWriter(f,fieldnames=['index','address','data','addr_type','data_type','operation','delay_us','slave_override'],lineterminator='\n');w.writeheader()
            for r in regs:w.writerow({**r,'address':f'0x{r["address"]:04x}','data':f'0x{r["data"]:02x}'})
    emit_c(out/'imx681-sp11-mode0-regs.h',init,mode)
    print(json.dumps(summary,indent=2))
    print('E003E_ORACLE_EXTRACTION=PASS')
if __name__=='__main__':main()
