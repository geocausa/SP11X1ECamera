"""Build camss module 49 = unified module 48 with the open front start-up profile.

The only change: the front profile loader reads qcom/sp11/imx681-front-open-v1.bin
(generated by gen-front-open-profile.py from published sources) and admits only
that file's SHA-256. The private profile name and digest are gone from the module.
imx681/ov13858 modules are reused from build 48 unchanged.
Usage: build-kernel49.py <open-profile.bin>  (gen-front-open-profile.py output). No install.
"""
import hashlib, json, shutil, subprocess, sys
from pathlib import Path

PROJECT = Path("/home/geoca/Documents/SP11-PROJECT")
BASE = PROJECT / "02-kernel/native-rgb-unified-48"
OUT = PROJECT / "02-kernel/native-rgb-unified-49"
KSOURCE = PROJECT / "02-kernel/e003i-front-production-src"
KOUTPUT = PROJECT / "02-kernel/build-runtime-v4-headers-20260826"
OLD_NAME = '"qcom/sp11/imx681-2560x1440-nv12-v1.bin"'
NEW_NAME = '"qcom/sp11/imx681-front-open-v1.bin"'


def rep(path, a, b):
    t = path.read_text()
    assert t.count(a) == 1, (path.name, a[:60])
    path.write_text(t.replace(a, b, 1))


def main():
    digest = hashlib.sha256(Path(sys.argv[1]).read_bytes()).digest()
    if OUT.exists():
        shutil.rmtree(OUT)
    OUT.mkdir()
    (OUT / "camss").mkdir()
    for p in (BASE / "camss").iterdir():
        if p.is_file() and (p.suffix in (".c", ".h", ".inc") or p.name in ("Makefile", "Kconfig")):
            shutil.copy2(p, OUT / "camss" / p.name)
    for name in ("imx681", "ov13858"):
        shutil.copytree(BASE / name, OUT / name)
    rep(OUT / "camss/native-front-profile.h", OLD_NAME, NEW_NAME)
    s = OUT / "camss/native-front-profile-schema.h"
    t = s.read_text()
    a = t.index("native_front_profile_digest[32] = {")
    b = t.index("};", a)
    t = t[:a] + "native_front_profile_digest[32] = {\n " + ", ".join("0x%02x" % x for x in digest) + " " + t[b:]
    t = t.replace(" * The fixed private qualification digest admits only this exact profile.\n",
                  " * The digest admits only the open profile generated from published sources\n"
                  " * (open-profile/gen-front-open-profile.py).\n")
    s.write_text(t)
    result = {"status": "BUILDING", "base": str(BASE), "profile_sha256": digest.hex()}
    try:
        with (OUT / "camss-compile.log").open("w") as log:
            subprocess.run(["make", "-C", str(KSOURCE), "O=" + str(KOUTPUT), "M=" + str(OUT / "camss"),
                            "CONFIG_VIDEO_QCOM_CAMSS=m", "W=1", "KCFLAGS=-Werror", "-j8", "modules"],
                           stdout=log, stderr=subprocess.STDOUT, check=True)
        ko = OUT / "camss/qcom-camss.ko"
        result["vermagic"] = subprocess.check_output(["modinfo", "-F", "vermagic", str(ko)], text=True).strip()
        fw = subprocess.check_output(["modinfo", "-F", "firmware", str(ko)], text=True).split()
        result["firmware"] = fw
        assert "qcom/sp11/imx681-front-open-v1.bin" in fw and "qcom/sp11/imx681-2560x1440-nv12-v1.bin" not in fw
        result["sha256"] = hashlib.sha256(ko.read_bytes()).hexdigest()
        result["status"] = "PASS_BUILD"
    except Exception as exc:
        result["status"] = "FAIL_BUILD"; result["error"] = str(exc); raise
    finally:
        (OUT / "build-result.json").write_text(json.dumps(result, indent=1) + "\n")
    print(json.dumps(result))


if __name__ == "__main__":
    main()
