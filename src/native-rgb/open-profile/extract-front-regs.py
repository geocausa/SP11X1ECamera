"""Lab tool: write the open register source for the front ISP startup profile.

Reads a lab reference profile (never published) only to recover the functional
register configuration observed on this machine, then applies the open-profile
decisions recorded in docs/FRONT-OPEN-PROFILE-*.md:

  * modules switched off in the open configuration (PDPC, GIC, the 0x5460
    stage and the tone mapper GTM): enable bit 0 cleared, every other
    configuration register of the module set to 0 (DMI bank selects kept);
  * BPC_ABF and BLS: our measured/swept values (the native_front_reg_mask list);
  * everything else: functional configuration (mode geometry, crop/round/clamp,
    scaler, statistics windows, enables, black-level pedestal, BT.601 transform,
    identity colour matrix) as observed.

Usage: extract-front-regs.py <schema.h> <reference.bin> <reg_mask csv> > regs.txt
No table byte of the reference is read or written.
"""
import collections
import sys
from frontprof import Schema, le

OFF = {  # module: (enable register, first config register, end)
    "PDPC": (0x3D60, 0x3D60, 0x3E00),
    "GIC": (0x4760, 0x4760, 0x4800),
    "BAYER_5460": (0x5460, 0x5460, 0x5500),
    "GTM": (0x5A60, 0x5A60, 0x5F00),
}
NAMES = [
    (0x0000, 0x0100, "top: core configuration"),
    (0x3B00, 0x3C00, "DEMUX: Bayer pattern, channel gains, pedestal"),
    (0x3D00, 0x3E00, "BPC_PDPC: switched off (open configuration)"),
    (0x3F00, 0x4000, "BINCORRECT"),
    (0x4300, 0x4400, "LSC: mesh geometry and interpolation for the 17x13 grid"),
    (0x4500, 0x4600, "WB_GAIN: start-up gains (the IPA writes per-frame gains)"),
    (0x4700, 0x4800, "GIC: switched off (open configuration)"),
    (0x4900, 0x4A00, "BPC_ABF: our registers (open-regs sweep, runs ae-44..74)"),
    (0x4B00, 0x4C00, "BLS: our measured pedestal (dark frames)"),
    (0x4D00, 0x4E00, "BAYER_GTM: off"),
    (0x5200, 0x5300, "LCAC: off"),
    (0x5400, 0x5500, "0x5460 stage: switched off (open configuration)"),
    (0x5600, 0x5700, "colour/level stage: generic constants"),
    (0x5800, 0x5900, "COLOR_CORRECT: identity (our CCM is applied by native_front_ccm_q7)"),
    (0x5A00, 0x5F00, "GTM tone mapper: switched off, curve registers zero"),
    (0x5F00, 0x6000, "GLUT gamma: enable and DMI bank selects (table generated)"),
    (0x6100, 0x6200, "COLOR_TRANSFORM: full-range BT.601 RGB->YUV (306/601/117 per 1024)"),
    (0x6300, 0x6400, "UVG: off"),
    (0x9800, 0xA000, "video path scalers and FULL crop/round/clamp (2560x1440 NV12 from 3840x2160)"),
    (0xA000, 0xA400, "DSX downscalers DS4/DS16: geometry (filter tables zero, outputs unused)"),
    (0xA400, 0xB000, "DS4/DS16 crop/round/clamp geometry"),
    (0xB000, 0xC000, "statistics: AEC BE, BF, BHIST, AWB BG, RS window geometry"),
]


def name(reg):
    for a, b, n in NAMES:
        if a <= reg < b:
            return n
    raise ValueError("unnamed register 0x%04x" % reg)


def main():
    schema = Schema(sys.argv[1])
    ref = open(sys.argv[2], "rb").read()
    masks = [int(x, 0) for x in sys.argv[3].split(",")] if len(sys.argv) > 3 else []
    masks = [masks[i:i + 3] for i in range(0, len(masks), 3)]
    vals = collections.defaultdict(dict)
    consts = {}
    for off, lab in schema.words.items():
        v = le(ref, off)
        if lab[0] == "reg":
            _, reg, sec = lab
            for r, a, o in masks:
                if r == reg and sec != "M":
                    v = (v & a) | o
            for mod, (en, first, end) in OFF.items():
                if first <= reg < end:
                    v = v & ~1 if reg == en else 0
            if vals[reg].get(sec, v) != v:
                raise ValueError("inconsistent duplicate for 0x%04x %s" % (reg, sec))
            vals[reg][sec] = v
        elif lab[0] == "const":
            consts[lab[1]] = v
    print("# SPDX-License-Identifier: GPL-2.0-only")
    print("# SP11 front (imx681) ISP start-up register configuration, 2560x1440 NV12.")
    print("# Generated by open-profile/extract-front-regs.py; see docs/FRONT-OPEN-PROFILE-20261015.md.")
    print("# Format: REG[@SECTION] VALUE. Sections: P0..P3 start-up packets, S steady packet,")
    print("# M steady per-module record. A line without a section applies to every section.")
    last = None
    ranged = set()
    for reg in sorted(vals):
        n = name(reg)
        if n != last:
            print("\n# %s" % n)
            last = n
        off = [m for m, (en, first, end) in OFF.items() if en < reg < end]
        if off:
            en, first, end = OFF[off[0]]
            if off[0] not in ranged:
                print("0x%04x..0x%04x 0x00000000" % (en + 4, end - 4))
                ranged.add(off[0])
            assert set(vals[reg].values()) == {0}
            continue
        per = vals[reg]
        common = collections.Counter(per.values()).most_common(1)[0][0]
        print("0x%04x 0x%08x" % (reg, common))
        for sec in sorted(per):
            if per[sec] != common:
                print("0x%04x@%s 0x%08x" % (reg, sec, per[sec]))
    print("\n# CDM dynamic values and per-module record words")
    for k in sorted(consts):
        print("%s 0x%08x" % (k, consts[k]))


if __name__ == "__main__":
    main()
