"""Use the existing exact-rational generator; no tuning input or refit."""
from pathlib import Path
import importlib.util,json,hashlib,sys
Q=Path(__file__).resolve().parent;R=Q.parents[3]
p=R/'src/upstream/isp-config/open_config.py'
spec=importlib.util.spec_from_file_location('retained_open_config',p)
m=importlib.util.module_from_spec(spec);sys.modules[spec.name]=m;spec.loader.exec_module(m)
matrix=[x for row in m.bt601_q10_gbr() for x in row]
assert all(sum(matrix[i:i+3])==(1024 if i==0 else 0) for i in [0,3,6])
text="""/* SPDX-License-Identifier: GPL-2.0-only */
/* Generated by generate-policy.py from the existing exact-rational BT.601
 * generator, input G,B,R.12-bit output offsets/range derive from powers of2.
 * Independent candidate policy, not equality with inherited private settings.
 */
#ifndef SP11_FRONT_CST12_POLICY_H
#define SP11_FRONT_CST12_POLICY_H

#include "sp11-front-cst12-config.h"

static const struct sp11_cst_config sp11_front_cst12_bt601 = {
\t.matrix = { """+', '.join(str(x) for x in matrix)+""" },
\t.offset = { 0, 1U << 11, 1U << 11 },
\t.maximum = { (1U << 12) - 1, (1U << 12) - 1, (1U << 12) - 1 },
};

static inline int
sp11_front_cst12_bt601_config(u8 *out, size_t capacity,
\t\t\t    const struct sp11_front_cold_policy *policy,
\t\t\t    unsigned int gamma_bits)
{
\treturn sp11_front_cst12_config(out, capacity, policy,
\t\t\t\t     &sp11_front_cst12_bt601, gamma_bits);
}
#endif
"""
lines=text.splitlines()
for i,line in enumerate(lines):
 if line.startswith('sp11_front_cst12_bt601_config('):
  col=line.index('(')+1;j=i+1
  while lines[j].lstrip().startswith(('const ','unsigned ')):
   lines[j]='\t'*(col//8)+' '*(col%8)+lines[j].lstrip();j+=1
text='\n'.join(lines)+'\n'
target=Q/'sp11-front-cst12-policy.h'
if '--check' in sys.argv:assert target.read_text()==text,'generated policy drift'
else:target.write_text(text)
print(json.dumps({'generated_policy_exact':True,'matrix_generator_sha256':hashlib.sha256(p.read_bytes()).hexdigest(),
 'input_order':'GBR','candidate_output_bits':12,'private_input':False,'calibration_refitted':False}))
